export interface TrophyData {
  id: string;
  season: string;
  category: string;
  title: string;
  shortTitle: string;
  fact: string;
  details: string;
  stats: Array<{label: string; value: string}>;
  silhouette: 'championship' | 'cup' | 'bronze' | 'firstLeague';
  accentColor: string;
  metalTint: number;
}

export interface PlayerPin {
  id: string;
  dossierKey: 'role' | 'number' | 'physique' | 'profile';
  label: string;
  shortTag: string;
  x: number; // percentage 0..100
  y: number; // percentage 0..100
}

export interface PlayerDossierBlock {
  key: 'role' | 'number' | 'physique' | 'profile';
  title: string;
  value: string;
  detail: string;
}

export interface PlayerData {
  id: string;
  fullName: string;
  firstName: string;
  lastName: string;
  jerseyLabel: string;
  number: string;
  role: string;
  birthDate: string;
  height: string;
  nationality: string;
  bio: string;
  extendedStory: string;
  traits: string[];
  accentHue: string;
  photoSrc: string;
  photoPosition: string;
  dossier: PlayerDossierBlock[];
  pins: PlayerPin[];
}

export interface HistoryMilestone {
  year: string;
  era: string;
  title: string;
  description: string;
}

export interface StadiumFact {
  index: string;
  label: string;
  value: string;
  note: string;
}

